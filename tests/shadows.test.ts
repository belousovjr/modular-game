function ownerScope() {
  const cleanups: (() => void)[] = [];
  return { onDispose: (cleanup: () => void) => { cleanups.push(cleanup); }, dispose: () => { for (const cleanup of cleanups.splice(0).reverse()) cleanup(); } };
}

test('bounded shadows follow active LODs, include offscreen casters, clear at night and restore owned state', t => {
  const engine = new NullEngine();
  const scene = new Scene(engine);
  const owner = ownerScope();
  t.after(() => { owner.dispose(); scene.dispose(); engine.dispose(); });
  const camera = new FreeCamera('camera', Vector3.Zero(), scene);
  const consumer = defineModule({ id: 'shadow-fixture', title: '', category: 'Тесты', requires: { geometry: geometryModule, templates: objectTemplatesModule, rendering: objectRenderingModule }, setup({ deps }) { return deps; } });
  let deps: ReturnType<typeof consumer.setup> | undefined;
  const capture = defineModule({ id: 'capture', title: '', category: 'Тесты', requires: { probe: consumer }, setup({ deps: values }) { deps = values.probe; return {}; } });
  const session = startModules([geometryModule, objectTemplatesModule, objectRenderingModule, consumer, capture], ['capture'], { scene, panels: createPanels(), onFrame: new Observable<number>() });
  owner.onDispose(() => session.dispose());
  assert.ok(deps);
  const { geometry, templates, rendering } = deps;
  const smallPart: GeometryPart = { surface: 'detail', size: [0.12, 0.15, 0.12], position: [2.06, 6, 0] };
  templates.register({ id: 'caster', version: 1, parameters: {}, build: () => ({ hideDistance: 300, levels: [0, 10].map((distance): TemplateLevel => ({ distance, parts: [{ surface: 'body', size: [4, 12, 4], position: [0, 6, 0] }, ...(distance === 0 ? [smallPart] : [])] })) }) }, owner);
  const near = rendering.createObject('caster', 'near', {}, owner, 'static');
  const offscreen = rendering.createObject('caster', 'offscreen', {}, owner, 'static'); offscreen.root.position.x = 40;
  const distant = rendering.createObject('caster', 'distant', {}, owner, 'static'); distant.root.position.x = 200;
  const ground = geometry.createModel('inclined-ground', [{ surface: 'floor', size: [1100, 0.3, 1100] }], owner);
  ground.root.rotation.z = 0.015;
  const groundMesh = ground.root.getChildMeshes()[0]; groundMesh.receiveShadows = true;
  templates.register({ id: 'slab', version: 1, parameters: {}, build: () => ({ hideDistance: 300, levels: [{ distance: 0, parts: [{ surface: 'floor', size: [20, 0.3, 20] }] }] }) }, owner);
  rendering.createObject('slab', 'batch-receiver', {}, owner, 'static', 'floor');
  const lighting = createLighting(scene, owner);
  const sun = lighting.getSunLight();
  const originalPosition = sun.position.clone();
  const originalLeft = sun.orthoLeft;
  const originalEnabled = sun.shadowEnabled;
  const frame = () => scene.onBeforeRenderObservable.notifyObservers(scene);
  for (let repeat = 0; repeat < 2; repeat++) {
    const shadowScope = ownerScope(); owner.onDispose(shadowScope.dispose);
    const shadows = createShadows(scene, sun, geometry.getMeshes, rendering.getDistanceOrigin, shadowScope);
    const generator = sun.getShadowGenerator(); assert.ok(generator instanceof ShadowGenerator);
    assert.equal(generator.forceBackFacesOnly, false);
    const map = generator.getShadowMap(); assert.ok(map);
    assert.throws(() => createShadows(scene, sun, geometry.getMeshes, rendering.getDistanceOrigin, ownerScope()), /уже/);
    assert.equal(sun.getShadowGenerator(), generator);
    assert.equal(map.getSize().width, shadows.getStats().mapSize);
    assert.equal(shadows.getStats().cascades, 1);
    assert.equal(shadows.getStats().halfSize, 80);
    assert.equal(shadows.getStats().mapSize, 1024);
    assert.equal(sun.orthoRight, 80);
    assert.equal(sun.orthoLeft, -80);
    camera.position.x = 0; frame();
    assert.equal(shadows.getStats().casters, 3);
    assert.ok(map.renderList?.some(mesh => mesh.name.includes('offscreen')));
    assert.ok(!map.renderList?.some(mesh => mesh.name.includes('distant')));
    assert.ok(!map.renderList?.includes(groundMesh));
    assert.ok(!map.renderList?.some(mesh => mesh.name.includes('surface-batch')));
    const detail = near.root.getChildMeshes().find(mesh => mesh.name.endsWith('/detail') && mesh.isEnabled());
    assert.ok(detail);
    assert.ok(map.renderList?.includes(detail));
    detail.isVisible = false; frame();
    assert.ok(!map.renderList?.includes(detail));
    detail.isVisible = true; frame();
    assert.ok(map.renderList?.includes(detail));
    const oldLOD = near.root.getChildMeshes().find(mesh => mesh.isEnabled()); assert.ok(oldLOD);
    assert.equal(oldLOD.receiveShadows, true);
    assert.ok([...geometry.getMeshes()].filter(mesh => mesh.hasThinInstances).every(mesh => mesh.receiveShadows));
    lighting.setSettings({ hour: 8 }); frame();
    const morningBias = generator.bias;
    lighting.setSettings({ hour: 12 }); frame();
    assert.ok(Number.isFinite(morningBias) && morningBias > generator.bias);
    assert.ok(generator.bias >= 0.0005);
    lighting.setSettings({ hour: 14 }); frame();
    const stablePosition = sun.position.clone();
    const revision = shadows.getStats().revision;
    frame(); assert.ok(sun.position.equalsWithEpsilon(stablePosition, 1e-6));
    assert.equal(shadows.getStats().revision, revision);
    camera.rotation.y += 0.3; frame();
    assert.equal(shadows.getStats().revision, revision);
    camera.rotation.y -= 0.3; frame();
    offscreen.root.position.y += 1; offscreen.refreshTransform(); frame();
    assert.ok(shadows.getStats().revision > revision);
    offscreen.root.position.y -= 1; offscreen.refreshTransform(); frame();
    camera.position.x = 20; frame();
    assert.ok(!map.renderList?.includes(oldLOD));
    assert.ok(!map.renderList?.includes(detail));
    assert.ok(map.renderList?.some(mesh => mesh.name.includes('near/lod-1')));
    camera.position.x = 400; frame();
    // Babylon adds enumerable methods to renderList; compare names, not its scene graph.
    assert.deepEqual(map.renderList?.map(mesh => mesh.name), []);
    assert.equal(shadows.getStats().enabled, false);
    camera.position.x = 0; frame();
    lighting.setSettings({ hour: 0 }); frame();
    assert.equal(shadows.getStats().enabled, false); assert.equal(sun.shadowEnabled, false); assert.equal(map.renderList?.length, 0);
    lighting.setSettings({ hour: 14 }); frame(); assert.equal(shadows.getStats().casters, 3);
    const noHero = ownerScope();
    rendering.setDistanceSource(() => null, noHero); frame(); assert.equal(map.renderList?.length, 0);
    noHero.dispose(); frame(); assert.equal(shadows.getStats().casters, 3);
    shadowScope.dispose();
    assert.equal(sun.getShadowGenerator(), null);
    assert.ok(sun.position.equals(originalPosition));
    assert.equal(sun.orthoLeft, originalLeft); assert.equal(sun.shadowEnabled, originalEnabled);
    assert.equal(oldLOD.receiveShadows, false); assert.equal(detail.receiveShadows, false); assert.equal(groundMesh.receiveShadows, true);
    assert.equal(scene.textures.length, 0);
    assert.throws(() => shadows.getStats(), /остановлены/);
  }
  const shadowScope = ownerScope(); owner.onDispose(shadowScope.dispose);
  createShadows(scene, sun, geometry.getMeshes, rendering.getDistanceOrigin, shadowScope);
  frame(); near.root.dispose(); frame();
  assert.ok(sun.getShadowGenerator()?.getShadowMap()?.renderList?.every(mesh => !mesh.isDisposed() && mesh.isEnabled() && !mesh.name.includes('near/')));
});


test('light-space culling rejects side misses but keeps occluders beyond depth planes', t => {
  const engine = new NullEngine();
  const scene = new Scene(engine);
  const owner = ownerScope();
  t.after(() => { owner.dispose(); scene.dispose(); engine.dispose(); });
  new FreeCamera('camera', Vector3.Zero(), scene);
  const mesh = MeshBuilder.CreateBox('probe', { size: 1 }, scene);
  mesh.metadata={shadowNearOnly:true};
  owner.onDispose(() => mesh.dispose());
  const light = createLighting(scene, owner).getSunLight();
  createShadows(scene, light, () => [mesh], () => ({ x: 0, y: 0, z: 0 }), owner);
  scene.onBeforeRenderObservable.notifyObservers(scene);
  const generator = light.getShadowGenerator();
  assert.ok(generator instanceof ShadowGenerator);
  const map = generator.getShadowMap(); assert.ok(map);
  generator.normalBias=3;
  map.onBeforeRenderObservable.notifyObservers(0);
  assert.equal(generator.normalBias,.12);
  map.onAfterRenderObservable.notifyObservers(0);
  assert.equal(generator.normalBias,.12);
  const subMesh = mesh.subMeshes[0]; assert.ok(subMesh);
  assert.equal(generator.customAllowRendering(subMesh), true);
  mesh.position.copyFrom(light.position).addInPlace(light.direction.scale(1000));
  mesh.computeWorldMatrix(true);
  assert.equal(generator.customAllowRendering(subMesh), true);
  mesh.position.x += 10000; mesh.computeWorldMatrix(true);
  assert.equal(generator.customAllowRendering(subMesh), false);
});


